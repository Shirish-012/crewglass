// Renders .claude/rules/crewglass-team.md — the team map Claude loads in every session in the folder.
// It carries the hand-off order, the direct-call rules (D18) and the checks, in plain words Claude follows.

import type { Agent, Check, DirectState, Link, LinkKind } from "./types";
import { isCostly, modelWithEffort } from "./models";
import { LEGACY } from "./legacy";

export const TEAM_MAP_FILE = ".claude/rules/crewglass-team.md";
/** Where the team map is in a folder: the current name, else the one saved under the old name (Agent Deck). */
export const TEAM_MAP_FILES = [TEAM_MAP_FILE, LEGACY.teamMap] as const;

/** The links you drew, by agent NAME, stored inside the team map so Crewglass can read them back. */
export interface TeamMapLink { from: string; to: string; kind: LinkKind; directState?: DirectState; check?: string }
export interface TeamMapData { version: 1; orchestrator: string | null; links: TeamMapLink[] }

/** Your Claude Code chat (the main session). It leads the team by default — only an agent you make the orchestrator
 *  takes over. On the canvas it's one card; in the team map's data it's this name. */
export const CHAT_KEY = "chat:main";
export const CHAT_NAME = "@chat";

const DATA_RE = /<!-- (?:crewglass|agent-deck):team (\{[\s\S]*?\}) -->/;

export function parseTeamMap(text: string): TeamMapData | null {
  const m = text.match(DATA_RE);
  if (!m) return null;
  try {
    const d = JSON.parse(m[1]) as TeamMapData;
    if (d.version !== 1 || !Array.isArray(d.links)) return null;
    d.links = d.links.filter((l) => typeof l.from === "string" && typeof l.to === "string" && ["delegates", "direct", "uses", "checkedBy"].includes(l.kind));
    return d;
  } catch { return null; }
}

export function renderTeamMap(opts: {
  agents: Agent[];
  links: Link[];
  checks: Record<string, Check>;
  orchestrator: Agent | null;
}): string {
  const { agents, links, checks, orchestrator } = opts;
  const name = (key: string) => (key === CHAT_KEY ? "your Claude Code chat" : agents.find((a) => a.key === key)?.name ?? key.split(":").pop() ?? key);
  const lead = orchestrator?.name ?? "Your Claude Code chat";
  const team = agents.filter((a) => a.kind !== "builtin" && !a.disabled);
  const out: string[] = [
    "# Crewglass team map",
    "",
    "Generated by Crewglass from the team you drew. Edit the team in Crewglass; changes here are overwritten.",
    "",
    orchestrator ? `Orchestrator: **${orchestrator.name}** (${modelWithEffort(orchestrator.model, orchestrator.effort)})`
      : "Orchestrator: **your Claude Code chat** (the main session) — there is no orchestrator agent. When a task matches an agent's role below, hand it to that agent; answer quick questions yourself. Don't hand the coordinating itself to another agent.",
    "",
    "## Agents",
  ];
  for (const a of team) {
    if (a.key === orchestrator?.key) continue;
    const model = a.kind === "agy" ? `agy · ${modelWithEffort(a.geminiModel ?? "")} (via Haiku relay)` : modelWithEffort(a.model, a.effort);
    out.push(`- **${a.name}**: ${a.role} (${model}${a.maxTurns ? `, max ${a.maxTurns} turn${a.maxTurns === 1 ? "" : "s"}` : ""})`);
  }

  const handOffs = links.filter((l) => l.planned && l.kind === "delegates");
  if (handOffs.length) {
    out.push("", "## Hand-offs", `${lead} hands work to: ${handOffs.map((l) => name(l.to)).join(", ")}.`);
  }

  const direct = links.filter((l) => l.planned && l.kind === "direct");
  out.push(
    "",
    "## Direct calls between agents",
    "To call another agent directly, the first line of your request must be `Reason: <why you need them>`.",
    "Direct calls go at most 2 levels deep, and each agent run may make at most 3.",
    ...(orchestrator ? [] : ["Here \"the orchestrator\" is the Claude Code chat that handed you the work."]),
  );
  const rule: Record<string, string> = {
    allowed: "allowed",
    orchestrator: "ask the orchestrator first: finish and reply with `REQUEST <agent>: <reason>`",
    you: "needs the user's approval (Crewglass will ask them)",
    blocked: "not allowed",
  };
  for (const l of direct) out.push(`- ${name(l.from)} → ${name(l.to)}: ${rule[l.directState ?? "orchestrator"]}`);
  const costly = team.filter((a) => a.key !== orchestrator?.key && isCostly(a.model, a.effort, a.kind === "agy")).map((a) => a.name);
  if (costly.length) out.push(`- Any other direct call to ${costly.join(", ")} (costly): needs the user's approval (Crewglass will ask them); if they don't answer within 2 minutes, ask the orchestrator.`);
  out.push("- Any other direct call: ask the orchestrator first.");

  const checked = team.filter((a) => a.checks.length || links.some((l) => l.kind === "checkedBy" && l.from === a.key && l.planned));
  const linkChecked = links.filter((l) => l.planned && l.checks?.length && (l.kind === "delegates" || l.kind === "direct"));
  if (checked.length || linkChecked.length) {
    out.push("", "## Checks", "Work is not done until its checks pass. Crewglass runs command checks when an agent that changed files finishes, sends failed work back to be fixed (at most 2 rounds), and tells the orchestrator the result.");
    for (const a of checked) {
      const names = a.checks.map((c) => checks[c]?.label ?? c);
      for (const l of links) if (l.kind === "checkedBy" && l.from === a.key && l.planned) names.push(`${name(l.to)} must answer VERDICT: PASS`);
      out.push(`- ${a.name}: ${names.join("; ")}`);
    }
    for (const l of linkChecked) out.push(`- ${name(l.to)}, when ${name(l.from)} hands it work: ${l.checks!.map((c) => checks[c]?.label ?? c).join("; ")}`);
  }
  out.push("", "## Finishing", orchestrator
    ? `${orchestrator.name} ends every task with a short report that includes a verification table: agent · what it did · checks and verdicts · result.`
    : "When you handed work to agents, end with a short report that includes a verification table: agent · what it did · checks and verdicts · result.");

  // Machine-readable copy of the drawn links (names only), so the canvas can be rebuilt from this file.
  const nameOf = (key: string) => (key.startsWith("mcp:") ? key : key === CHAT_KEY ? CHAT_NAME : name(key));
  const data: TeamMapData = {
    version: 1,
    orchestrator: orchestrator?.name ?? null,
    links: links.filter((l) => l.planned).map((l) => ({
      from: nameOf(l.from), to: nameOf(l.to), kind: l.kind,
      ...(l.kind === "direct" ? { directState: l.directState ?? "allowed" } : {}),
      ...(l.check ? { check: l.check.label } : {}),
    })),
  };
  const json = JSON.stringify(data).replace(/</g, "\\u003c").replace(/>/g, "\\u003e"); // a "-->" in a label can't end the comment
  out.push("", `<!-- crewglass:team ${json} -->`, "");
  return out.join("\n");
}
